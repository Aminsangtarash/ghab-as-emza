export function getLearnCategory(slug: string) {
  return learnCategories.find((item) => item.slug === slug);
}

export function getLearnArticle(slug: string) {
  return learnArticles.find((item) => item.slug === slug);
}

export function learnArticlesByCategory(slug: string) {
  return learnArticles.filter((item) => item.categorySlug === slug);
}

export function relatedLearnArticles(article: LearnArticle, limit = 3) {
  return learnArticles
    .filter((item) => item.categorySlug === article.categorySlug && item.slug !== article.slug)
    .slice(0, limit);
}
